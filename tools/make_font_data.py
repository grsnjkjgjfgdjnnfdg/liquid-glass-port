"""Generate the embedded font header the port expects, from any TTF.

The working copy embeds SF Pro as C arrays; that font cannot be redistributed, so this
produces a header with the same symbol names from a face that can be - Inter, under the
SIL Open Font License. The port's type metrics differ a little as a result, which the
README states.

    python tools/make_font_data.py --regular Inter-Regular.ttf --semibold ... \
        --bold ... --out fonts/FontsGenerated.h
"""

from __future__ import annotations

import argparse
from pathlib import Path


def emit(name: str, data: bytes) -> str:
    body = ",".join(str(b) for b in data)
    return (f"static const unsigned char {name}[] = {{{body}}};\n"
            f"static const unsigned int {name}_size = {len(data)};\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--regular", required=True)
    ap.add_argument("--semibold", required=True)
    ap.add_argument("--bold", required=True)
    ap.add_argument("--out", default="fonts/FontsGenerated.h")
    args = ap.parse_args()

    regular = Path(args.regular).read_bytes()
    semibold = Path(args.semibold).read_bytes()
    bold = Path(args.bold).read_bytes()

    out = ["// Generated by tools/make_font_data.py - do not edit.\n",
           "// Inter, SIL Open Font License 1.1.\n#pragma once\n"]
    out.append(emit("sfp_text_regular_data", regular))
    out.append(emit("sfp_text_semibold_data", semibold))
    out.append(emit("sfp_text_bold_data", bold))
    out.append(emit("sfp_display_bold_data", bold))
    out.append(emit("sfp_display_semibold_data", semibold))
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("".join(out), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
