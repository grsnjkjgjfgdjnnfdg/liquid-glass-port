"""Generate the embedded font header the port expects, from any TTF.

The working copy embeds SF Pro as C arrays; that font cannot be redistributed, so this
produces a header with the same symbol names from a face that can be - Inter, under the
SIL Open Font License. The port's type metrics differ a little as a result, which the
README states.

    python tools/make_font_data.py --regular Inter-Regular.ttf --semibold ... \
        --bold ... --out fonts/FontsGenerated.h
"""

from __future__ import annotations

import argparse
from pathlib import Path


def emit(stem: str, data: bytes) -> str:
    """A named blob in the port's convention: `<stem>_data[]` plus `<stem>_size`."""
    body = ",".join(str(b) for b in data)
    return (f"static const unsigned char {stem}_data[] = {{{body}}};\n"
            f"static const unsigned int {stem}_size = {len(data)};\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--regular", required=True)
    ap.add_argument("--semibold", required=True)
    ap.add_argument("--bold", required=True)
    ap.add_argument("--out", default="fonts/FontsGenerated.h")
    args = ap.parse_args()

    regular = Path(args.regular).read_bytes()
    semibold = Path(args.semibold).read_bytes()
    bold = Path(args.bold).read_bytes()

    out = ["// Generated by tools/make_font_data.py - do not edit.\n",
           "// Inter, SIL Open Font License 1.1.\n#pragma once\n"]
    out.append(emit("sfp_text_regular", regular))
    out.append(emit("sfp_text_semibold", semibold))
    out.append(emit("sfp_text_bold", bold))
    out.append(emit("sfp_display_bold", bold))
    out.append(emit("sfp_display_semibold", semibold))

    # The legacy fallback path types these as `const unsigned int *`, so they are
    # pointers onto the same bytes rather than arrays of a different element type.
    out.append(emit("sfpro_font_payload", regular))
    out.append(emit("sfpro_semibold_payload", semibold))
    out.append("static const unsigned int* const sfpro_font_data =\n"
               "    (const unsigned int*)sfpro_font_payload_data;\n")
    out.append("static const unsigned int* const sfpro_semibold_data =\n"
               "    (const unsigned int*)sfpro_semibold_payload_data;\n")
    out.append(f"static const unsigned int sfpro_font_size = {len(regular)};\n")
    out.append(f"static const unsigned int sfpro_semibold_size = {len(semibold)};\n")

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("".join(out), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
